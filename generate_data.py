"""
Generate a dataset from LAMMPS data files.
This script converts LAMMPS data files into a numpy format suitable for
training machine learning models.
The generated dataset contains the following information:
- Neighbor list of atoms
- Label (phase of the material)
- Temperature
- Original LAMMPS data filename

The neighbor list is generated by randomly sampling points in the box
of the LAMMPS data file.
"""

import argparse
import sys
import tempfile
from logging import INFO, StreamHandler, getLogger
from pathlib import Path

import arbol_kd as akd
import numpy as np
from lammps_io import data as lio
from tqdm import tqdm

import na_dataset_util as nads_util
from na_dataset_dataset_builder import Builder

# Set up logging
logger = getLogger(__name__)
handler = StreamHandler(sys.stdout)

logger.addHandler(handler)

logger.setLevel(INFO)
handler.setLevel(INFO)


def lammps_data2npz(
    ifile: Path,
    odir: Path,
    *,
    num_sampling: int = 1000,
    num_atoms: int = nads_util.DEFAULT_NUM_ATOMS,
    phase: str | None = None,
    overwrite: bool = False,
) -> list[Path]:
    """
    Convert LAMMPS data file to numpy format.

    Args:
        ifile (Path): Input LAMMPS data file.
        odir (Path): Output directory for results.
        num_sampling (int): Number of sampling points per file.
        num_atoms (int): Number of atoms to include in the output.
        phase (str | None): Phase of the material (liquid, fcc, bcc, hcp).
        overwrite (bool): Whether to overwrite existing files.

    Returns:
        list[Path]: List of output files generated relative to the odir.
    """
    label = ifile.parent.name
    if phase is None:
        label = ifile.parent.name
    else:
        label = phase

    if not nads_util.validate_label(label):
        logger.error(
            "Invalid phase name: %s. Please use one of the following: %s",
            label,
            ", ".join(nads_util.PHASE_LABELS),
        )
        sys.exit(1)

    temperature = float(ifile.name.split(".")[1].replace("K", ""))

    lmp_data = lio.read(ifile)
    atom_poses = lio.get_atom_poses(lmp_data)
    box = lio.get_xyz_regions(lmp_data)
    tree = akd.build_tree_3d(atom_poses)

    # Randomly select points in the box
    sampling_num = num_sampling
    random_points = (
        np.random.rand(sampling_num, 3) * (box[:, 1] - box[:, 0]) + box[:, 0]
    )
    ofiles = []

    for target_point in tqdm(random_points, desc=f"Sampling {ifile.name}"):
        # sort the data by distance from target_point
        neighbor_atoms = akd.k_nearest_periodic(tree, target_point, box, num_atoms)
        neighbor_atoms = (
            akd.clamp2nearest(neighbor_atoms, target_point, box)[:] - target_point
        )

        ds_content = nads_util.NaDataset(
            atoms=neighbor_atoms[:num_atoms].astype(dtype=np.float32),
            label=label,
            temperature=np.float32(temperature),
            original_lammps_data_filename=ifile.name,
        )

        try:
            ofile = nads_util.write_dataset(odir, ds_content, overwrite=overwrite)
        except FileExistsError as e:
            logger.error(e)
            sys.exit(1)

        ofiles.append(ofile.relative_to(odir))

    logger.debug("Phase: %s", label)
    logger.debug("Temperature: %.1f", temperature)
    logger.debug("Number of atoms: %d", num_atoms)
    logger.debug("Number of sampling points: %d", num_sampling)

    return ofiles


def zip_data_dir(data_dir: Path, zip_path: Path, *, overwrite: bool = False):
    """
    Zip the data directory into a zip file.
    """
    if zip_path.exists() and not overwrite:
        logger.error(
            "Zip file %s already exists. Please remove it or use a different output path.",
            zip_path,
        )
        sys.exit(1)
    import subprocess

    subprocess.run(
        ["zip", "-rq", str(zip_path.resolve()), "."], cwd=str(data_dir), check=True
    )
    logger.info("Zipped '%s' → '%s'", data_dir, zip_path)


def main(inputs: list[str], args: dict):
    """
    Main function to convert LAMMPS data files to numpy format.
    Args:
        inputs (list[str]): List of input LAMMPS data files.
        args (dict): Dictionary of additional arguments for conversion.
    """
    np.random.seed(args["seed"])
    base_path = Path(__file__).parent
    odir = Path(f"na_dataset.{Builder.VERSION}")
    zip_path = base_path / f"na_dataset.{Builder.VERSION}.zip"
    if zip_path.exists():
        logger.error("Zip file %s already exists.", zip_path)
        logger.error("Please remove it or use a different output path.")
        sys.exit(1)

    logger.info("Starting dataset generation with version %s", Builder.VERSION)
    logger.info("Arguments %s", args)
    with tempfile.TemporaryDirectory() as tmpdir:
        odir = Path(tmpdir) / odir
        odir.mkdir(parents=True, exist_ok=True)

        ofiles = []
        for i in inputs:
            i = Path(i)
            if i.is_dir():
                for file in i.glob("**/data.*"):
                    ret = lammps_data2npz(
                        ifile=file,
                        odir=odir,
                        num_sampling=args["num_sampling"],
                        num_atoms=args["num_atoms"],
                        phase=args["phase"],
                        overwrite=False,
                    )
                    ofiles.extend(ret)
            elif i.is_file():
                ret = lammps_data2npz(ifile=i, **args)
                ofiles.extend(ret)

        if len(ofiles) == 0:
            logger.error("No files generated. Please check the input files.")
            sys.exit(1)

        logger.info("Total number of file generated: %d under %s", len(ofiles), odir)
        try:
            nads_util.write_train_test_txt(
                odir=odir, ofiles=ofiles, split=args["split"], overwrite=False
            )
        except FileExistsError as e:
            logger.error(e)
            sys.exit(1)

        logger.info("Generating dataset zip file...")
        zip_data_dir(odir, zip_path, overwrite=False)


